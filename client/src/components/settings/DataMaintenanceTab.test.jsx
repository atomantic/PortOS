import { beforeEach, expect, it, vi } from 'vitest';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router';
const api = vi.hoisted(() => vi.fn());
vi.mock('../../services/apiCore', () => ({ request: api }));
import DataMaintenanceTab from './DataMaintenanceTab';
const rows = [{ id: 'retired-training-runs', label: 'Retired artifacts', path: 'data/training-runs', category: 'Unique checkpoints', status: 'retained', warning: 'Unique files', bytes: 17, files: 1, actions: ['delete'] }];
const preview = { token: 'example-token', confirmation: 'DELETE training-runs', path: 'data/training-runs', bytes: 17, files: 1, warning: 'Unique files' };
beforeEach(() => { api.mockReset(); api.mockResolvedValue(rows); });
const mount = () => render(<MemoryRouter><DataMaintenanceTab /></MemoryRouter>);
it('requires preview and exact typed confirmation, supports cancellation, prevents repeated clicks and updates inventory after success', async () => {
  mount(); await screen.findByText('Retired artifacts');
  api.mockResolvedValueOnce(preview);
  fireEvent.click(screen.getByRole('button', { name: 'Preview deletion' }));
  await screen.findByRole('dialog');
  expect(screen.getByRole('button', { name: 'Permanently delete' })).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));
  expect(screen.queryByRole('dialog')).toBeNull();
  expect(api).toHaveBeenCalledTimes(2);
  api.mockResolvedValueOnce(preview);
  fireEvent.click(screen.getByRole('button', { name: 'Preview deletion' }));
  await screen.findByRole('dialog');
  fireEvent.change(screen.getByRole('textbox'), { target: { value: 'DELETE training-runs' } });
  let finish;
  api.mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  fireEvent.click(screen.getByRole('button', { name: 'Permanently delete' }));
  fireEvent.click(screen.getByRole('button', { name: 'Removing…' }));
  expect(api).toHaveBeenCalledTimes(4);
  await act(async () => { finish({ operationId: rows[0].id, removedBytes: 17, removedFiles: 1, status: 'deleted', remainingBytes: 0, remainingFiles: 0 }); });
  expect(screen.queryByRole('dialog')).toBeNull();
  expect(screen.getByText('absent')).toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'Preview deletion' })).toBeNull();
});
it('surfaces stale-preview refusal, preserves the row, and permits explicit refresh', async () => {
  mount(); await screen.findByText('Retired artifacts');
  api.mockResolvedValueOnce(preview);
  fireEvent.click(screen.getByRole('button', { name: 'Preview deletion' }));
  await screen.findByRole('dialog');
  fireEvent.change(screen.getByRole('textbox'), { target: { value: preview.confirmation } });
  api.mockRejectedValueOnce(new Error('Files changed since preview'));
  fireEvent.click(screen.getByRole('button', { name: 'Permanently delete' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Files changed since preview');
  expect(screen.getByText('retained')).toBeInTheDocument();
  api.mockResolvedValueOnce(rows);
  fireEvent.click(screen.getByRole('button', { name: 'Refresh' }));
  await waitFor(() => expect(screen.queryByRole('alert')).toBeNull());
});
it('shows an unreadable inventory as unavailable instead of measured zero and blocks refresh during initial load', async () => {
  let complete;
  api.mockImplementationOnce(() => new Promise(resolve => { complete = resolve; }));
  mount();
  expect(screen.getByRole('button', { name: 'Refresh' })).toBeDisabled();
  complete([{ ...rows[0], status: 'unavailable', bytes: null, files: null, error: 'Directory cannot be read', actions: [] }]);
  expect(await screen.findByText(/Size unavailable/)).toBeInTheDocument();
  expect(screen.getByRole('alert')).toHaveTextContent('Directory cannot be read');
  expect(screen.queryByText('0 B')).toBeNull();
  expect(screen.queryByRole('button', { name: 'Preview deletion' })).toBeNull();
});
