#!/usr/bin/env node
/**
 * Render a scheduled task type's agent prompt end-to-end — shipped prompt
 * default → pre-step block substitution → `buildAgentPrompt` — and print the
 * byte size of every `## ` section, so a context audit starts from numbers
 * instead of guesses about which block is fat.
 *
 *   node scripts/measure-agent-prompt.js [taskType] [providerType] [--out <prefix>]
 *
 *   taskType      a DEFAULT_TASK_PROMPTS key (default: claim-issue)
 *   providerType  tui (light path, split system/user prompt), cli, or api
 *                 (full path: instruction files, memory, tools; default: tui)
 *   --out         also write <prefix>.user.md / <prefix>.system.md
 *
 * Runs against the shipped defaults with placeholder app/reviewer values and
 * NO database (NODE_ENV=test + MEMORY_BACKEND=file are forced), so the numbers
 * are the prompt's own cost, not this install's. Set REPO=<path> to point the
 * api path's instruction-file walk at a real checkout.
 */
import { writeFileSync } from 'fs';

process.env.NODE_ENV = 'test';
process.env.MEMORY_BACKEND ||= 'file';

const args = process.argv.slice(2);
const outIndex = args.indexOf('--out');
const outPrefix = outIndex === -1 ? null : args[outIndex + 1];
const positional = outIndex === -1 ? args : args.filter((_, i) => i !== outIndex && i !== outIndex + 1);
const taskType = positional[0] || 'claim-issue';
const providerType = positional[1] || 'tui';

const [{ getTaskPrompt }, { buildImprovementTaskDescription }, { buildAgentPrompt }] = await Promise.all([
  import('../server/services/taskPromptService.js'),
  import('../server/services/cosTaskPreStepBlocks.js'),
  import('../server/services/agentPromptBuilder.js'),
]);

const app = { id: 'example-app', name: 'Example App', repoPath: process.env.REPO || '/repo/example' };
const template = await getTaskPrompt(taskType, { claimFlow: true });
const metadata = {
  app: app.id, appName: app.name, repoPath: app.repoPath, analysisType: taskType,
  autoGenerated: true, claimFlow: true, reviewers: ['antigravity', 'ollama'], useWorktree: false, openPR: false,
};
const emptyBlocks = Object.fromEntries([
  'referenceData', 'trackerInstructions', 'modeInstructions', 'prData', 'inFlightBranches',
  'zombieIssues', 'repoSyncReport', 'repoFullName', 'defaultBranch', 'planConstraint',
].map((key) => [key, '']));
const description = await buildImprovementTaskDescription({
  promptTemplate: template, app, promptTaskType: taskType, metadata, blocks: emptyBlocks,
});
const task = { id: 'task-measure', description, metadata, taskType: 'internal' };
const isApi = providerType === 'api';
const result = await buildAgentPrompt(task, {}, app.repoPath, null, undefined, {
  providerType,
  providerId: isApi ? 'example-api' : 'claude-code',
  providerCommand: isApi ? null : 'claude',
  providerModel: 'example-model',
  agentId: 'agent-measure',
  split: !isApi,
});
const userPrompt = typeof result === 'string' ? result : result.userPrompt;
const systemPrompt = typeof result === 'string' ? '' : (result.systemPrompt || '');

// ~4 chars/token is close enough to rank sections; it is not a tokenizer.
const tokens = (text) => Math.round(text.length / 4);
const sections = (text) => text.split(/\n(?=## )/).map((s) => [s.split('\n')[0].slice(0, 72), s.length]);
const printSections = (label, text) => {
  console.log(`--- ${label} (${text.length}B, ~${tokens(text)} tok)`);
  for (const [heading, size] of sections(text)) console.log(`${String(size).padStart(7)}  ${heading}`);
};

console.log(`${taskType} via ${providerType}: template=${template.length}B description=${description.length}B total≈${tokens(userPrompt + systemPrompt)} tok`);
printSections('user prompt', userPrompt);
if (systemPrompt) printSections('system prompt', systemPrompt);
if (outPrefix) {
  writeFileSync(`${outPrefix}.user.md`, userPrompt);
  writeFileSync(`${outPrefix}.system.md`, systemPrompt);
  console.log(`📝 Wrote ${outPrefix}.user.md and ${outPrefix}.system.md`);
}
