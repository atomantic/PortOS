#!/usr/bin/env node
/**
 * Generate `server/scripts/init-db.sql`, the fresh-install schema, from the
 * schema modules ensureSchema() runs at boot (#16092).
 *
 * The modules under `server/lib/db/schema/` are the single DDL source: running
 * installs get exactly their statements on every boot, so a fresh install's SQL
 * is derived from them rather than hand-mirrored. The output is the hand-written
 * `server/scripts/init-db.base.sql` (extensions, the memory system's own tables,
 * and the memory trigger) with its marker line replaced by every statement of
 * `buildUpgradeDdl()` then `buildCatalogDdl()`, in boot order.
 *
 * The path stays fixed: Docker mounts it as an initdb script, and
 * `server/scripts/setup-db-test.mjs`, `scripts/db.sh` and
 * `scripts/rehearsal-scratch-db.js` apply it.
 *
 * The output depends only on statement text and order, never on where a
 * statement sits in its module, so unrelated edits to a schema module leave the
 * file unchanged. `scripts/generate-init-db-sql.test.js` fails when the
 * committed file is stale.
 *
 * Usage:  node scripts/generate-init-db-sql.js           # write the file
 *         node scripts/generate-init-db-sql.js --check   # exit 1 when stale
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDirectlyInvoked } from './lib/directInvocation.js';
import { buildCatalogDdl, buildUpgradeDdl } from '../server/lib/db/schema/index.js';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const INIT_DB_SQL_PATH = join(REPO_ROOT, 'server', 'scripts', 'init-db.sql');
export const INIT_DB_BASE_PATH = join(REPO_ROOT, 'server', 'scripts', 'init-db.base.sql');
export const SCHEMA_MODULES_MARKER = '-- @portos:schema-modules';

const HEADER = [
  '-- GENERATED by scripts/generate-init-db-sql.js — do not edit by hand.',
  '-- Source: server/scripts/init-db.base.sql + the server/lib/db/schema/ modules',
  '-- (buildUpgradeDdl() then buildCatalogDdl(), the statements ensureSchema()',
  '-- runs on every boot). Change a schema module or the base file, then run',
  '-- `node scripts/generate-init-db-sql.js`.',
  '',
].join('\n');

// Statement text is emitted verbatim (only trimmed): re-indenting would change
// stored function bodies and could alter a multi-line string literal, and the
// fresh-install catalog must match what ensureSchema() leaves on a running install.
/** One psql-runnable statement, terminated by exactly one `;`. */
export const formatStatement = (statement) => {
  if (typeof statement !== 'string' || !statement.trim()) {
    throw new Error('schema module statement must be a non-empty SQL string');
  }
  return `${statement.trim().replace(/;\s*$/, '')};`;
};

/**
 * The base file split at its marker: `before` runs ahead of the module
 * statements, `after` behind them. Its leading comment block documents the
 * base file itself, so it is not carried into the generated file.
 */
export const splitInitDbBase = (base) => {
  const parts = base.replace(/^(?:--[^\n]*\n)+\n/, '').split(`${SCHEMA_MODULES_MARKER}\n`);
  if (parts.length !== 2) {
    throw new Error(`init-db.base.sql must contain the marker line "${SCHEMA_MODULES_MARKER}" exactly once`);
  }
  return { before: parts[0], after: parts[1] };
};

/** The generated init-db.sql text for a base file and two ordered statement lists. */
export const renderInitDbSql = ({ base, upgradeDdl, catalogDdl }) => {
  const { before, after } = splitInitDbBase(base);
  const statements = [...upgradeDdl, ...catalogDdl].map(formatStatement).join('\n\n');
  return `${HEADER}\n${before}${statements}\n${after}`;
};

/** The init-db.sql the current schema modules and base file produce. */
export const generateInitDbSql = () => renderInitDbSql({
  base: readFileSync(INIT_DB_BASE_PATH, 'utf8'),
  upgradeDdl: buildUpgradeDdl(),
  catalogDdl: buildCatalogDdl(),
});

if (isDirectlyInvoked(import.meta.url)) {
  const generated = generateInitDbSql();
  if (process.argv.includes('--check')) {
    const committed = readFileSync(INIT_DB_SQL_PATH, 'utf8');
    if (committed !== generated) {
      console.error('❌ server/scripts/init-db.sql is stale — run: node scripts/generate-init-db-sql.js');
      process.exit(1);
    }
    console.log('✅ server/scripts/init-db.sql matches the schema modules');
  } else {
    writeFileSync(INIT_DB_SQL_PATH, generated);
    console.log('🗄️ Wrote server/scripts/init-db.sql from the schema modules');
  }
}
