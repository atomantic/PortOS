/**
 * Keeps the generated "All other documents" block of docs/README.md in sync
 * with every docs/**\/*.md file the hand-written tables do not link. The block
 * is derived, so parallel branches never hand-edit (and conflict on) it; run
 * `node scripts/sync-docs-index.js` to rewrite it or `--check` to fail when stale.
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join, relative } from 'path';
import { fileURLToPath } from 'url';
import { isDirectlyInvoked } from './lib/directInvocation.js';

const DOCS_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs');
export const BEGIN = '<!-- docs-index:begin (generated by scripts/sync-docs-index.js; do not edit) -->';
export const END = '<!-- docs-index:end -->';

export const listDocs = (dir = DOCS_DIR) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) return listDocs(full);
    return entry.name.endsWith('.md') ? [relative(DOCS_DIR, full).split('\\').join('/')] : [];
  }).sort();

const titleOf = (rel) => {
  const heading = readFileSync(join(DOCS_DIR, rel), 'utf8').match(/^#\s+(.+)$/m);
  return heading ? heading[1].trim() : rel;
};

const splitReadme = (readme) => {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error('docs/README.md is missing the docs-index markers');
  return { head: readme.slice(0, start), tail: readme.slice(end + END.length) };
};

/** Pure: returns the README text with the generated block rebuilt. */
export function renderReadme(readme, docs, titles) {
  const { head, tail } = splitReadme(readme);
  const linked = (rel) => new RegExp(`\\]\\((\\./)?${rel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(#[^)]*)?\\)`).test(head + tail);
  const missing = docs.filter((rel) => rel !== 'README.md' && !rel.endsWith('/README.md') && !linked(rel));
  const groups = Map.groupBy(missing, (rel) => (rel.includes('/') ? rel.split('/')[0] : 'top level'));
  const lines = [BEGIN, ''];
  for (const [group, files] of groups) {
    lines.push(`**${group}**`, '');
    for (const rel of files) lines.push(`- [${titles[rel]}](./${rel})`);
    lines.push('');
  }
  lines.push(END);
  return head + lines.join('\n') + tail;
}

if (isDirectlyInvoked(import.meta.url)) {
  const path = join(DOCS_DIR, 'README.md');
  const readme = readFileSync(path, 'utf8');
  const docs = listDocs();
  const next = renderReadme(readme, docs, Object.fromEntries(docs.map((rel) => [rel, titleOf(rel)])));
  if (process.argv.includes('--check')) {
    if (next !== readme) { console.log('⚠️ docs/README.md generated index is stale; run node scripts/sync-docs-index.js'); process.exit(1); }
  } else if (next !== readme) {
    writeFileSync(path, next);
    console.log('✅ docs/README.md generated index updated');
  }
}
